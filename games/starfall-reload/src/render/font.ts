export const FONT_CHARS = Object.keys(GLYPHS).join("");
export const GLYPH_W = 5,
    GLYPH_H = 7,
    CELL_W = 7,
    CELL_H = 9,
    ADVANCE = 6;

/** Renders the font as one strip of 7×9 cells: white ink with a baked dark outline. */
export function renderFont(): Pixels {
    const chars = [...FONT_CHARS];
    const p = new Pixels(chars.length * CELL_W, CELL_H);
    chars.forEach((ch, i) => {
        const rows = normalise(GLYPHS[ch]!);
        for (let y = 0; y < GLYPH_H; y++)
            for (let x = 0; x < GLYPH_W; x++) if (rows[y * GLYPH_W + x] === "#") p.set(i * CELL_W + 1 + x, 1 + y, 0xffffff);
    });
    // Outline per cell so neighbouring glyphs never merge.
    const out = new Pixels(p.w, p.h);
    out.data.set(p.data);
    for (let y = 0; y < p.h; y++)
        for (let x = 0; x < p.w; x++) {
            if (p.alpha(x, y)) continue;
            const cell = Math.floor(x / CELL_W);
            const inCell = (xx: number) => Math.floor(xx / CELL_W) === cell;
            const near =
                (inCell(x - 1) && p.alpha(x - 1, y)) ||
                (inCell(x + 1) && p.alpha(x + 1, y)) ||
                p.alpha(x, y - 1) ||
                p.alpha(x, y + 1) ||
                (inCell(x + 1) && p.alpha(x + 1, y + 1)) ||
                (inCell(x - 1) && p.alpha(x - 1, y + 1));
            if (near) out.set(x, y, 0x0b0d1a, 230);
        }
    return out;
}

/** Glyph strings are written row-major without separators; pad/trim defensively to 35. */
function normalise(rows: string): string {
    return rows.padEnd(GLYPH_W * GLYPH_H, ".").slice(0, GLYPH_W * GLYPH_H);
}

export function glyphIndex(ch: string): number {
    const i = FONT_CHARS.indexOf(ch);
    return i >= 0 ? i : FONT_CHARS.indexOf("?");
}

export const textWidth = (text: string, scale = 1): number => [...text].length * ADVANCE * scale - scale;
